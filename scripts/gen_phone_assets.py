#!/usr/bin/env python3
"""Embed Resources/phone/{index.html,app.css,app.js} into Sources/Thon/Phone/PhoneAssets.swift.

The phone web client is served from memory by the app (like the Metal shaders), so it needs no bundle resources.
Edit the files in Resources/phone/, then run:  python3 scripts/gen_phone_assets.py
`--check` exits 1 if the generated file is out of date (the picker tests also check this).
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "Resources", "phone")
OUT = os.path.join(ROOT, "Sources", "Thon", "Phone", "PhoneAssets.swift")
FILES = [("indexHTML", "index.html"), ("appJS", "app.js"), ("appCSS", "app.css")]

def build():
    out = ["// GENERATED by scripts/gen_phone_assets.py from Resources/phone/. Do not edit by hand.", "enum PhoneAssets {"]
    for name, f in FILES:
        text = open(os.path.join(SRC, f), encoding="utf-8").read()
        if '"""###' in text or "\\###" in text:
            sys.exit("asset %s contains a raw-string delimiter" % f)
        out.append("    static let %s = ###\"\"\"\n%s\n\"\"\"###" % (name, text.rstrip("\n")))
    out.append("}")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    new = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if cur == new else 1)
    open(OUT, "w", encoding="utf-8").write(new)
    print("wrote", OUT, len(new), "bytes")
